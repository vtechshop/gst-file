async function buildCanonical(tables = canonicalTables()) {
  ctx._supabase = makeDataSupabase(tables);
  const res = await ctx.buildGSTR1Payload(
    US, { gstin: OWN, state: 'Tamil Nadu', business_name: 'Dummy Co' }, '2026-07');
  assert.ok(!res.errors || !res.errors.length,
    'the canonical build reported errors: ' + JSON.stringify((res.errors || []).slice(0, 3)));
  // Round-tripped: the payload is built inside the browser-context realm, so
  // its objects carry that realm's prototypes and deepStrictEqual would fail
  // on identity alone. This also compares what actually gets WRITTEN.
  return JSON.parse(JSON.stringify(res.payload));
}

// Structural signature: key names and nesting, with every leaf reduced to its
// type. Two payloads with the same signature differ only in business values.
function signature(value) {
  if (Array.isArray(value)) return value.length ? [signature(value[0])] : [];
  if (value && typeof value === 'object') {
    const out = {};
    Object.keys(value).sort().forEach(k => { out[k] = signature(value[k]); });
    return out;
  }
  return typeof value;
}

