test('FL6. emitWhenEmpty behaviour is unchanged: an empty section is omitted, not written as []', async () => {
  const t = canonicalTables();
  t.cdn_notes = [];
  t.receipt_vouchers = [];
  t.advance_adjustments = [];
  const p = await buildCanonical(t);
  ['cdnr', 'cdnur', 'at', 'txpd'].forEach(k =>
    assert.ok(!(k in p), `an empty ${k} must be omitted entirely, as in the accepted file`));
  ['gstin', 'fp', 'version', 'hash'].forEach(k =>
    assert.ok(k in p, `header key "${k}" is written even on a sparse return`));
});

// ── C. The five named regression guards ────────────────────────────

test('N1 — ATADJ GUARD: Table 11B is txpd, and "atadj" appears nowhere', async () => {
  const p = await buildCanonical();
  assert.ok('txpd' in p, 'Table 11B must be emitted under "txpd" (Portal ref 57a4038d)');
  assert.ok(!('atadj' in p), '"atadj" must never be a root key (Portal REFUSED it, ref 925b681d)');
  assert.ok(!JSON.stringify(p).includes('atadj'),
    '"atadj" must not appear anywhere in the written file at any depth');
});

test('N2 — ADVANCE POS GUARD: a state name becomes a two-digit POS code', async () => {
  const p = await buildCanonical();
  // The fixture stores place_of_supply as "Tamil Nadu". Emitting that verbatim
  // is what the Portal rejected before c952daf.
  [['at', p.at], ['txpd', p.txpd]].forEach(([name, section]) => {
    assert.ok(Array.isArray(section) && section.length, `${name} must carry rows in this fixture`);
    section.forEach(g => {
      assert.strictEqual(g.pos, '33',
        `${name}.pos must be the two-digit code for Tamil Nadu, got ${JSON.stringify(g.pos)}`);
      assert.match(String(g.pos), /^[0-9]{2}$/,
        `${name}.pos must be two digits, never a state name`);
    });
  });
});

test('N3 — CDNR INV_TYP GUARD: every credit/debit note carries inv_typ', async () => {
  const p = await buildCanonical();
  assert.ok(Array.isArray(p.cdnr) && p.cdnr.length, 'cdnr must carry rows in this fixture');
  p.cdnr.forEach(group => group.nt.forEach(note => {
    assert.ok('inv_typ' in note,
      `cdnr note ${note.nt_num} is missing inv_typ — the Portal refuses the file without it `
      + '(ref 4a091bb2 refused, 065ee200 accepted once it was added)');
    assert.strictEqual(typeof note.inv_typ, 'string', 'inv_typ must be a string');
  }));
});

test('N4 — EXP FLAT ITMS GUARD: exp items are flat, never num/itm_det', async () => {
  const p = await buildCanonical();
  assert.ok(Array.isArray(p.exp) && p.exp.length, 'exp must carry rows in this fixture');
  p.exp.forEach(group => group.inv.forEach(e => {
    e.itms.forEach(itm => {
      assert.deepStrictEqual(Object.keys(itm).sort(), ['csamt', 'iamt', 'rt', 'txval'],
        'exp itms rows are flat {txval, rt, iamt, csamt} — nesting them was tried and REFUSED '
        + '(ref 118344b3)');
      assert.ok(!('num' in itm), 'exp itms must not carry "num"');
      assert.ok(!('itm_det' in itm), 'exp itms must not carry "itm_det"');
    });
  }));
});

test('N5 — SHIPPING BILL DATA GUARD: a numeric sbnum is emitted unchanged, as a string', async () => {
  // A guard on the accepted behaviour only. It adds no validation and blocks
  // no export — the numeric rule is a property of the DATA, and a production
  // validator for it was deliberately not introduced here.
  const p = await buildCanonical();
  const exports_ = p.exp.flatMap(g => g.inv);
  assert.ok(exports_.length, 'exp must carry invoices in this fixture');
  exports_.forEach(e => {
    assert.strictEqual(e.sbnum, '9000001',
      'the shipping bill number must be emitted exactly as stored');
    assert.strictEqual(typeof e.sbnum, 'string',
      'sbnum is a string in the accepted format, never a number');
    assert.match(e.sbnum, /^[0-9]{3,15}$/,
      'the accepted data is 3-15 digits — an alphanumeric value was REFUSED (ref 0c657af6)');
  });
});
