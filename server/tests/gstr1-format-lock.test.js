  ['b2b', 'b2cl', 'b2cs', 'cdnr', 'cdnur', 'exp', 'at', 'txpd', 'nil', 'hsn', 'doc_issue']
    .forEach(k => assert.ok(k in p, `section "${k}" is missing — this fixture is meant to cover every section`));
