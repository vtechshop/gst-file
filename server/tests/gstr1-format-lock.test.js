// GSTR-1 FORMAT LOCK.
//
// The July 2026 return was accepted by the GST Portal (ref
// 7634d93b-a07a-4f1d-a995-7dc75b8a4765, and again as
// d915821e-bb31-4924-9085-aeac8137a537). That file's STRUCTURE is now the
// canonical production format. Monthly data changes; the format does not.
//
// Getting there took twelve uploads, because the Portal answers a structural
// problem with one generic sentence and names no field. Each defect below was
// isolated by adding one section at a time to a known-accepted baseline:
//
//   + b2cl                          accepted  6f7ed599
//   + cdnr                          REFUSED   4a091bb2   -> missing inv_typ
//   + cdnr with inv_typ:"R"         accepted  065ee200
//   + cdnur                         accepted  7c33b553
//   + exp (alphanumeric sbnum)      REFUSED   0c657af6   -> sbnum must be digits
//   + exp with nested itms          REFUSED   118344b3   -> flat was right all along
//   + exp (numeric sbnum, flat)     accepted  bc791dd3
//   + at                            accepted  bff59a63
//   + atadj                         REFUSED   925b681d   -> wrong key name
//   + txpd (same bytes, renamed)    accepted  57a4038d
//   + nil — the complete return     accepted  7634d93b
//
// These tests exist so none of that has to be discovered twice. They assert
// STRUCTURE, never business values: no amount, date, GSTIN or invoice number
// from any real return appears here or in the fixture.
//
// The fixture is generated by the exporter itself over deterministic dummy
// input, so it records what the code actually produces rather than what
// someone believed it produced. If a change to the exporter is deliberate and
// the Portal has confirmed the new shape, the fixture is updated in the same
// commit — and the commit message is expected to carry the Portal reference
// that justifies it.
